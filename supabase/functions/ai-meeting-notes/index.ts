import { serve } from "https://deno.land/std@0.168.0/http/server.ts";
import { cap, MAX_DOCUMENT_CHARS, MAX_FILENAME_CHARS } from "../_shared/limits.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const body = await req.json();
    const textContent = cap(body.textContent, MAX_DOCUMENT_CHARS);
    const filename = cap(body.filename, MAX_FILENAME_CHARS) || "document.pdf";
    const pageCount = Number(body.pageCount) || 1;
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const systemContent = `You are an expert meeting notes analyst. The user uploaded "${filename}" (${pageCount} pages). Analyze the document and extract structured meeting notes. Return your analysis in this exact markdown format:

## 📋 Meeting Overview
- **Date**: (extract if available)
- **Participants**: (list attendees if mentioned)
- **Topic/Agenda**: (main subject)

## ✅ Action Items
List every action item, task, or to-do mentioned. For each:
- [ ] **Task description** — Assigned to: (person if mentioned) — Deadline: (if mentioned)

## 🎯 Key Decisions
List all decisions that were made during the meeting:
1. **Decision**: description and context

## 💡 Key Discussion Points
Summarize the main topics discussed with brief context for each.

## 📌 Important Takeaways
The most critical points someone who missed the meeting should know.

## ⚠️ Open Questions / Follow-ups
List any unresolved questions or items needing follow-up.

Be thorough and extract every actionable item. If the document doesn't appear to be meeting notes, still extract action items, decisions, and key points as best you can.

Here is the document text:

${textContent}`;

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          { role: "system", content: systemContent },
          { role: "user", content: "Extract all action items, decisions, key points, and follow-ups from this document." },
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) return new Response(JSON.stringify({ error: "Rate limited" }), { status: 429, headers: { ...corsHeaders, "Content-Type": "application/json" } });
      if (response.status === 402) return new Response(JSON.stringify({ error: "Payment required" }), { status: 402, headers: { ...corsHeaders, "Content-Type": "application/json" } });
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      throw new Error("AI gateway error");
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("meeting-notes error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
